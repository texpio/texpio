use crate::{
    commands::{metadata, notifications, preferences, recovery},
    probe_commands,
};
use specta_typescript::{BigIntExportBehavior, Typescript};

pub fn builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::new().commands(tauri_specta::collect_commands![
        metadata::get_app_info,
        preferences::load_preferences,
        preferences::save_preferences,
        preferences::migrate_legacy_theme,
        recovery::save_emergency_data,
        recovery::load_emergency_data,
        recovery::cleanup_old_recovery_files,
        notifications::send_native_notification,
        probe_commands::probe_status,
        probe_commands::probe_fixtures,
        probe_commands::probe_start,
        probe_commands::probe_stop,
        probe_commands::probe_pause,
        probe_commands::probe_exclude,
    ])
}

pub fn export_text() -> Result<String, specta_typescript::ExportError> {
    builder().export_str(
        Typescript::default()
            .bigint(BigIntExportBehavior::Number)
            .header("// @ts-nocheck\n// Auto-generated by bun run rust:bindings. Do not edit."),
    )
}

pub fn export() -> Result<(), Box<dyn std::error::Error>> {
    let text = export_text()?;
    let destination =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/bindings.ts");
    std::fs::write(destination, text)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn public_bindings_are_deterministic_and_exclude_native_context() {
        let first = super::export_text().unwrap();
        assert_eq!(first, super::export_text().unwrap());
        for private in [
            "TargetToken",
            "TargetStamp",
            "HWND",
            "IUIAutomation",
            "process_id",
            "ObservedCandidate",
        ] {
            assert!(!first.contains(private), "private native type exported");
        }
        assert!(first.contains("export type ProbeError = { code: RefusalReason }"));
        assert!(first.contains("submitted: number"));
    }
}
