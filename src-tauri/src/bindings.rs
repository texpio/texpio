pub fn export_text() -> Result<String, specta_typescript::ExportError> {
    builder().export_str(
        Typescript::default()
            .bigint(BigIntExportBehavior::Number)
            .header("// @ts-nocheck\n// Auto-generated by bun run rust:bindings. Do not edit."),
    )
}

pub fn export() -> Result<(), Box<dyn std::error::Error>> {
    let text = export_text()?;
    let destination =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/bindings.ts");
    std::fs::write(destination, text)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn public_bindings_are_deterministic_and_exclude_native_context() {
        let first = super::export_text().unwrap();
        assert_eq!(first, super::export_text().unwrap());
        for private in [
            "TargetToken",
            "TargetStamp",
            "HWND",
            "IUIAutomation",
            "process_id",
            "ObservedCandidate",
        ] {
            assert!(!first.contains(private), "private native type exported");
        }
        assert!(first.contains("export type ProbeError = { code: RefusalReason }"));
        assert!(first.contains("submitted: number"));
    }
}
